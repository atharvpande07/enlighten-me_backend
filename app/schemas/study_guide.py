from typing import List, Optional, Literal
from pydantic import BaseModel, Field


class TimelineItem(BaseModel):
    timestamp_start: str = Field(..., description="Start timestamp of the section in MM:SS or HH:MM:SS format")
    timestamp_end: str = Field(..., description="End timestamp of the section in MM:SS or HH:MM:SS format")
    topic: str = Field(..., description="Specific academic concept or section title")
    summary: str = Field(..., description="Synthesis of explanations given in this segment")


class ActionItem(BaseModel):
    category: Literal["exam_hint", "assignment", "deadline", "reading"] = Field(
        ...,
        description="Strict category of the action item"
    )
    detail: str = Field(..., description="Actionable instruction, deadline, or exam guidance")
    approximate_timestamp: Optional[str] = Field(
        None,
        description="Approximate timestamp in MM:SS when this item was mentioned by the lecturer"
    )


class StudyGuideContent(BaseModel):
    is_valid_lecture: bool = Field(
        ...,
        description="True if the recording contains audible academic lecture speech; False if noise, static, or unintelligible"
    )
    warning_banner: Optional[str] = Field(
        None,
        description="Amber warning message if audio quality was low, or partial summary generated. Null if clear audio."
    )
    overall_summary: str = Field(
        ...,
        description="High-level synthesis of the entire lecture in clear academic English"
    )
    timestamped_timeline: List[TimelineItem] = Field(
        default_factory=list,
        description="Chronological topic-by-topic segments with time anchors"
    )
    chronological_notes: List[str] = Field(
        default_factory=list,
        description="Structured markdown bullet points of core concepts and definitions"
    )
    action_items: List[ActionItem] = Field(
        default_factory=list,
        description="Extracted academic action items, exam tips, homework, and deadlines"
    )
    whatsapp_share_text: str = Field(
        ...,
        description="Formatted markdown with emojis and clear sections designed for 1-tap WhatsApp study group sharing"
    )


class LectureProcessResponse(BaseModel):
    lecture_id: str = Field(..., description="Database UUID string of the created lecture record")
    remaining_fup_seconds: int = Field(..., description="Remaining seconds available in user's Fair Usage Policy quota")
    study_guide: StudyGuideContent = Field(..., description="Structured study guide generated by AI")


class ErrorResponse(BaseModel):
    detail: str


class FupExceededErrorResponse(BaseModel):
    error_code: str = "FUP_EXCEEDED"
    detail: str
